class DisneyLand{
  static String location;
  static int numberOfRides;
  static float ticketPrice;
  static boolean isOpenToday;
  static double area;
  
  public static String getlocation(){
	  location = "California";
	  return location;
  }
  public static int getnumberOfRides(){
	  numberOfRides = 50;
	  return numberOfRides;
  }
  public static float getticketPrice(){
	  ticketPrice = 120.0f;
	  return ticketPrice;
  }
  public static boolean getisOpenToday(){
	  isOpenToday = true;
	  return isOpenToday;
  }
  public static double getarea(){
	  area = 500.0; 
	  return area;
  }
}




