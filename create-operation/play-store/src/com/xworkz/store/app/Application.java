package com.xworkz.store.app;

public class Application {
    private String version;
    private String updatedOn;
    private String downloads;
    private String updateSize;
    private String requiredOs;
    private String inappPurchase;
    private String offeredBy;
    private String releaseOn;

    public String getVersion() {
        return version;
    }

    public void setVersion(String version) {
        this.version = version;
    }

    public String getUpdatedOn() {
        return updatedOn;
    }

    public void setUpdatedOn(String updatedOn) {
        this.updatedOn = updatedOn;
    }

    public String getDownloads() {
        return downloads;
    }

    public void setDownloads(String downloads) {
        this.downloads = downloads;
    }

    public String getUpdateSize() {
        return updateSize;
    }

    public void setUpdateSize(String updateSize) {
        this.updateSize = updateSize;
    }

    public String getRequiredOs() {
        return requiredOs;
    }

    public void setRequiredOs(String requiredOs) {
        this.requiredOs = requiredOs;
    }

    public String getInappPurchase() {
        return inappPurchase;
    }

    public void setInappPurchase(String inappPurchase) {
        this.inappPurchase = inappPurchase;
    }

    public String getOfferedBy() {
        return offeredBy;
    }

    public void setOfferedBy(String offeredBy) {
        this.offeredBy = offeredBy;
    }

    public String getReleaseOn() {
        return releaseOn;
    }

    public void setReleaseOn(String releaseOn) {
        this.releaseOn = releaseOn;
    }
}
